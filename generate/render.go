type (
	Files struct {
		SDK []byte
		CLI []byte
		MCP []byte
	}

	opView struct {
		ID          string
		GoName      string
		Command     string
		Method      string
		Path        string
		Description string
		SideEffect  string
		SideConst   string
		Confirm     bool
		Permissions []string
		BaseURL     string
		Params      []paramView
	}

	paramView struct {
		Name        string
		GoName      string
		In          string
		Required    bool
		Description string
		Schema      string
		MediaType   string
		Default     string
	}
)

func Render(module string, cat *catalog.Catalog) (Files, error) {
	if module == "" {
		return Files{}, fmt.Errorf("module path required")
	}
	views := views(cat)
	sdk, err := render("sdk", sdkTmpl, map[string]any{"Ops": views})
	if err != nil {
		return Files{}, err
	}
	cli, err := render("cli", cliTmpl, map[string]any{"Module": module, "Ops": views})
	if err != nil {
		return Files{}, err
	}
	mcp, err := render("dispatch", dispatchTmpl, map[string]any{"Module": module, "Ops": views})
	if err != nil {
		return Files{}, err
	}
	return Files{SDK: sdk, CLI: cli, MCP: mcp}, nil
}

func views(cat *catalog.Catalog) []opView {
	ops := append([]catalog.Operation(nil), cat.Operations...)
	sort.Slice(ops, func(i, j int) bool { return ops[i].ID < ops[j].ID })
	usedCmd := map[string]int{}
	usedGo := map[string]int{}
	out := make([]opView, 0, len(ops))
	for _, op := range ops {
		goName := unique(usedGo, goName(op.ID))
		cmd := unique(usedCmd, commandName(op.ID))
		var params []paramView
		usedArg := map[string]int{}
		for _, p := range op.Params {
			params = append(params, paramView{
				Name:        p.Name,
				GoName:      unique(usedArg, argName(p.Name)),
				In:          p.In,
				Required:    p.Required || p.In == "path",
				Description: p.Description,
				Schema:      p.Schema,
				MediaType:   p.MediaType,
				Default:     p.Default,
			})
		}
		out = append(out, opView{
			ID:          op.ID,
			GoName:      goName,
			Command:     cmd,
			Method:      op.Method,
			Path:        op.PathTemplate,
			Description: op.Description,
			SideEffect:  string(op.SideEffect),
			SideConst:   sideConst(op.SideEffect),
			Confirm:     op.RequiresConfirmation,
			Permissions: op.Permissions,
			BaseURL:     op.BaseURL,
			Params:      params,
		})
	}
	return out
}

func unique(seen map[string]int, name string) string {
	if seen[name] == 0 {
		seen[name] = 1
		return name
	}
	seen[name]++
	return fmt.Sprintf("%s%d", name, seen[name])
}

func goName(id string) string {
	parts := strings.FieldsFunc(id, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	})
	var b strings.Builder
	for _, p := range parts {
		b.WriteString(export(p))
	}
	s := b.String()
	if s == "" || unicode.IsDigit(rune(s[0])) {
		s = "Op" + s
	}
	return s
}

func commandName(id string) string {
	if i := strings.LastIndex(id, "."); i >= 0 && i < len(id)-1 {
		id = id[i+1:]
	}
	return strings.ToLower(id)
}

func argName(name string) string {
	parts := strings.FieldsFunc(name, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	})
	if len(parts) == 0 {
		return "arg"
	}
	s := strings.ToLower(parts[0])
	for _, p := range parts[1:] {
		s += export(p)
	}
	if !token.IsIdentifier(s) || token.IsKeyword(s) {
		s = "arg" + export(s)
	}
	return s
}

func export(s string) string {
	if s == "" {
		return ""
	}
	r := []rune(s)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}

func sideConst(s catalog.SideEffect) string {
	switch s {
	case catalog.SideEffectNone:
		return "catalog.SideEffectNone"
	case catalog.SideEffectWrite:
		return "catalog.SideEffectWrite"
	case catalog.SideEffectDestructive:
		return "catalog.SideEffectDestructive"
	default:
		return "catalog.SideEffect(" + strconv.Quote(string(s)) + ")"
	}
}

func quoteList(ss []string) string {
	if len(ss) == 0 {
		return "[]string{}"
	}
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = strconv.Quote(s)
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}

func render(name, src string, data any) ([]byte, error) {
	tmpl, err := template.New(name).Funcs(template.FuncMap{
		"quote": strconv.Quote,
		"list":  quoteList,
	}).Parse(src)
	if err != nil {
		return nil, fmt.Errorf("parse %s template: %w", name, err)
	}
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("render %s: %w", name, err)
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format %s: %w\n%s", name, err, buf.String())
	}
	return out, nil
}
